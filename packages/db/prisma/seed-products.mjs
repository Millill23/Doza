// USD → BYN (примерный курс). Розлив: цена за мл × наценка за мелкий объём.
const USD_BYN = 3.3;
const MK = { 2: 2.5, 5: 2.0, 10: 1.7, 30: 1.4 };
function volumes(usd, bottleMl) {
  const perMl = (usd * USD_BYN) / bottleMl;
  return [2, 5, 10, 30].map((v) => ({
    volumeMl: v,
    priceByn: Math.round(perMl * v * MK[v] * 100) / 100,
    isActive: true,
  }));
}
function slugify(s) {
  return s
    .toLowerCase()
    .replace(/&/g, " ")
    .replace(/[`'’.]/g, "")
    .replace(/[^a-z0-9а-я]+/gi, "-")
    .replace(/(^-|-$)/g, "");
}

